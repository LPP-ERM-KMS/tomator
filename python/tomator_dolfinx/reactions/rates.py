# Create interpolator for H2 ionization (lazy initialization)
_h2_ioni_interp = None

def _RRH2_IONI(Te: np.ndarray, ne_cgs: np.ndarray) -> np.ndarray:
    """
    H2 electron-impact ionization rate coefficient from Dirk W. tables.
    e + H2 -> 2e + H2+
    
    Parameters
    ----------
    Te : np.ndarray
        Electron temperature [eV].
    ne_cgs : np.ndarray
        Electron density [cm^-3].
        
    Returns
    -------
    k : np.ndarray
        Rate coefficient [cm³/s].
    """
    from scipy.interpolate import RegularGridInterpolator
    
    global _h2_ioni_interp
    if _h2_ioni_interp is None:
        # Create 2D interpolator: axes are (Te, ne), values are k
        _h2_ioni_interp = RegularGridInterpolator(
            (_H2_TE_GRID, _H2_NE_GRID),
            _H2_IONI_TABLE,
            method='linear',
            bounds_error=False,
            fill_value=None  # Use nearest for extrapolation
        )
    
    # Ensure arrays
    Te = np.atleast_1d(Te)
    ne_cgs = np.atleast_1d(ne_cgs)
    
    # Clamp to table bounds (matching C++ behavior)
    Te_clamped = np.clip(Te, 0.1, 100.0)
    ne_clamped = np.clip(ne_cgs, 1e-6 * 1e15, 1e-6 * 1e18)  # 1e9 to 1e12 cm^-3
    
    # Interpolate
    points = np.column_stack([Te_clamped.ravel(), ne_clamped.ravel()])
    k = _h2_ioni_interp(points)
    
    # Apply minimum threshold (matching C++ k < 1e-20 -> 0)
    k = np.where(k < 1e-20, 0.0, k)
    
    return k.reshape(Te.shape)


def _RRH2_RECO(Te: np.ndarray) -> np.ndarray:
    """
    H2+ recombination to ground state H2 rate coefficient (approximate formula).
    e + H2+ -> H2  (produces molecular H2, NOT 2H atoms!)
    
    From reactionrates.cpp RECO case - uses approximate formula from Dirk W.
    For the dissociative channel producing 2H, use REAC2214 instead.
    
    Parameters
    ----------
    Te : np.ndarray
        Electron temperature [eV].
        
    Returns
    -------
    k : np.ndarray
        Rate coefficient [cm³/s].
    """
    Te = np.atleast_1d(Te)
    
    # Approximate formula from C++ reactionrates.cpp
    # k = 7.1e-20 * pow(Te/300.0, -2.7/3.0) * 0.5e6 + 7.1e-20 * pow(Te/1.0, -15.0/3.0) * 0.5e6
    k = (7.1e-20 * np.power(Te / 300.0, -2.7 / 3.0) * 0.5e6 + 
         7.1e-20 * np.power(Te / 1.0, -15.0 / 3.0) * 0.5e6)
    
    # Apply minimum threshold (matching C++ k < 1e-20 -> 0)
    k = np.where(k < 1e-20, 0.0, k)
    
    return k


