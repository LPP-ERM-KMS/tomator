def coulomb_log_ee(ne: np.ndarray, Te: np.ndarray) -> np.ndarray:
    """
    Electron-electron Coulomb logarithm.
    
    λ_ee = 23.5 - ln(sqrt(ne) * Te^(-1.25)) - sqrt(1e-5 + (ln(Te)-2)²/16)
    
    Parameters
    ----------
    ne : np.ndarray
        Electron density [cm^-3].
    Te : np.ndarray
        Electron temperature [eV].
        
    Returns
    -------
    lambda_ee : np.ndarray
        Coulomb logarithm (dimensionless).
    """
    Te_safe = np.maximum(Te, 0.01)
    ne_safe = np.maximum(ne, 1.0)
    
    term1 = np.log(np.sqrt(ne_safe) * np.power(Te_safe, -1.25))
    term2 = np.sqrt(1e-5 + (np.log(Te_safe) - 2.0)**2 / 16.0)
    
    return np.clip(23.5 - term1 - term2, 10.0, 20.0)


def coulomb_log_ei(ne: np.ndarray, Te: np.ndarray, Z: float = 1.0) -> np.ndarray:
    """
    Electron-ion Coulomb logarithm.
    
    λ_ei = 23 - ln(sqrt(ne) * Z * Te^(-3/2))
    
    Parameters
    ----------
    ne : np.ndarray
        Electron density [cm^-3].
    Te : np.ndarray
        Electron temperature [eV].
    Z : float
        Ion charge number.
        
    Returns
    -------
    lambda_ei : np.ndarray
        Coulomb logarithm (dimensionless), clipped to [10, 20].
    """
    Te_safe = np.maximum(Te, 0.01)
    ne_safe = np.maximum(ne, 1.0)
    
    lam = 23.0 - np.log(np.sqrt(ne_safe) * Z * np.power(Te_safe, -1.5))
    return np.clip(lam, 10.0, 20.0)


def coulomb_log_ii(n1: np.ndarray, T1: np.ndarray, Z1: float, mu1: float,
                   n2: np.ndarray, T2: np.ndarray, Z2: float, mu2: float) -> np.ndarray:
    """
    Ion-ion Coulomb logarithm.
    
    λ_ij = 23 - ln(Z1*Z2*(mu1+mu2)/(mu1*T2+mu2*T1) * sqrt(Z1²*n1/T1 + Z2²*n2/T2))
    
    Parameters
    ----------
    n1, n2 : np.ndarray
        Ion densities [cm^-3].
    T1, T2 : np.ndarray
        Ion temperatures [eV].
    Z1, Z2 : float
        Ion charge numbers.
    mu1, mu2 : float
        Ion mass numbers [amu].
        
    Returns
    -------
    lambda_ii : np.ndarray
        Coulomb logarithm (dimensionless), clipped to [10, 20].
    """
    T1_safe = np.maximum(T1, 0.01)
    T2_safe = np.maximum(T2, 0.01)
    n1_safe = np.maximum(n1, 1.0)
    n2_safe = np.maximum(n2, 1.0)
    
    denom = mu1 * T2_safe + mu2 * T1_safe
    term_inside = Z1**2 * n1_safe / T1_safe + Z2**2 * n2_safe / T2_safe
    
    arg = Z1 * Z2 * (mu1 + mu2) / denom * np.sqrt(term_inside)
    arg = np.maximum(arg, 1e-30)  # Prevent log(0)
    
    lam = 23.0 - np.log(arg)
    return np.clip(lam, 10.0, 20.0)


def nu_ee(ne: np.ndarray, Te: np.ndarray) -> np.ndarray:
    """
    Electron-electron collision frequency [1/s].
    
    ν_ee = 2.91e-6 * ne * λ_ee * Te^(-3/2)
    
    Parameters
    ----------
    ne : np.ndarray
        Electron density [cm^-3].
    Te : np.ndarray
        Electron temperature [eV].
        
    Returns
    -------
    nu : np.ndarray
        Collision frequency [1/s].
    """
    Te_safe = np.maximum(Te, 0.01)
    lam = coulomb_log_ee(ne, Te)
    return 2.91e-6 * ne * lam * np.power(Te_safe, -1.5)


def nu_ei(ne: np.ndarray, Te: np.ndarray, ni: np.ndarray, Ti: np.ndarray,
          Z: float = 1.0, mu: float = 1.0) -> np.ndarray:
    """
    Electron-ion collision frequency [1/s].
    
    ν_ei = ni * q^4 * 8*sqrt(2π) * λ / (3 * me * mi * (Te/me + Ti/mi)^1.5)
    
    Parameters
    ----------
    ne : np.ndarray
        Electron density [cm^-3].
    Te : np.ndarray
        Electron temperature [eV].
    ni : np.ndarray
        Ion density [cm^-3].
    Ti : np.ndarray
        Ion temperature [eV].
    Z : float
        Ion charge number.
    mu : float
        Ion mass number [amu].
        
    Returns
    -------
    nu : np.ndarray
        Collision frequency [1/s].
    """
    Te_safe = np.maximum(Te, 0.01)
    Ti_safe = np.maximum(Ti, 0.01)
    
    # Convert temperatures to erg
    TTe = _EV_TO_ERG * Te_safe
    TTi = _EV_TO_ERG * Ti_safe
    
    # Masses in g
    me = _ME_CGS * 1000.0  # me in milligrams for consistent units
    mi = mu * _MI_CGS * 1000.0
    
    lam = coulomb_log_ei(ne, Te, Z)
    
    # Collision frequency formula (Z^2 factor for higher charges)
    thermal_term = np.power(TTe / me + TTi / mi, 1.5)
    nu = ni * _Q_CGS**4 * Z**2 * 8.0 * np.sqrt(2.0 * np.pi) * lam / (3.0 * me * mi * thermal_term)
    
    return np.maximum(nu, 0.0)


def Q_ei(ne: np.ndarray, Te: np.ndarray, ni: np.ndarray, Ti: np.ndarray,
         Z: float = 1.0, mu: float = 1.0) -> np.ndarray:
    """
    Electron-ion energy exchange rate [eV·cm^-3/s].
    
    Q = (Te - Ti) * ν_ei * ne
    
    This is the power density transferred from electrons to ions.
    
    Parameters
    ----------
    ne : np.ndarray
        Electron density [cm^-3].
    Te : np.ndarray
        Electron temperature [eV].
    ni : np.ndarray
        Ion density [cm^-3].
    Ti : np.ndarray
        Ion temperature [eV].
    Z : float
        Ion charge number.
    mu : float
        Ion mass number [amu].
        
    Returns
    -------
    Q : np.ndarray
        Energy exchange rate [eV·cm^-3/s].
    """
    nu = nu_ei(ne, Te, ni, Ti, Z, mu)
    return (Te - Ti) * nu * ne


def nu_ii(n1: np.ndarray, T1: np.ndarray, Z1: float, mu1: float,
          n2: np.ndarray, T2: np.ndarray, Z2: float, mu2: float) -> np.ndarray:
    """
    Ion-ion collision frequency [1/s].
    
    ν_ij = n2 * q^4 * Z1²*Z2² * 8*sqrt(2π) * λ / (3 * m1 * m2 * (T1/m1 + T2/m2)^1.5)
    
    Parameters
    ----------
    n1, n2 : np.ndarray
        Ion densities [cm^-3].
    T1, T2 : np.ndarray
        Ion temperatures [eV].
    Z1, Z2 : float
        Ion charge numbers.
    mu1, mu2 : float
        Ion mass numbers [amu].
        
    Returns
    -------
    nu : np.ndarray
        Collision frequency [1/s].
    """
    T1_safe = np.maximum(T1, 0.01)
    T2_safe = np.maximum(T2, 0.01)
    
    # Convert temperatures to erg
    TT1 = _EV_TO_ERG * T1_safe
    TT2 = _EV_TO_ERG * T2_safe
    
    # Masses in g
    m1 = mu1 * _MI_CGS * 1000.0
    m2 = mu2 * _MI_CGS * 1000.0
    
    lam = coulomb_log_ii(n1, T1, Z1, mu1, n2, T2, Z2, mu2)
    
    # Collision frequency
    thermal_term = np.power(TT1 / m1 + TT2 / m2, 1.5)
    nu = n2 * _Q_CGS**4 * Z1**2 * Z2**2 * 8.0 * np.sqrt(2.0 * np.pi) * lam / (3.0 * m1 * m2 * thermal_term)
    
    return np.maximum(nu, 0.0)


def Q_ii(n1: np.ndarray, T1: np.ndarray, Z1: float, mu1: float,
         n2: np.ndarray, T2: np.ndarray, Z2: float, mu2: float) -> np.ndarray:
    """
    Ion-ion energy exchange rate [eV·cm^-3/s].
    
    Q = (T1 - T2) * ν_12 * n1
    
    This is the power density transferred from species 1 to species 2.
    
    Parameters
    ----------
    n1, n2 : np.ndarray
        Ion densities [cm^-3].
    T1, T2 : np.ndarray
        Ion temperatures [eV].
    Z1, Z2 : float
        Ion charge numbers.
    mu1, mu2 : float
        Ion mass numbers [amu].
        
    Returns
    -------
    Q : np.ndarray
        Energy exchange rate [eV·cm^-3/s].
    """
    nu = nu_ii(n1, T1, Z1, mu1, n2, T2, Z2, mu2)
    return (T1 - T2) * nu * n1


def ndamp(n_cgs: np.ndarray, nevac: float = 1.0) -> np.ndarray:
    """
    Density damping factor from C++ Tomator1D (functions.cpp line 392).
    
    ndamp(n) = (1 + nevac/n)^(-0.66)
    
    This limits reactions at very low densities (approaching vacuum).
    
    Parameters
    ----------
    n_cgs : np.ndarray
        Density [cm^-3].
    nevac : float
        Vacuum density reference [cm^-3]. Default is 1.0 from C++ simparam.cpp.
        
    Returns
    -------
    factor : np.ndarray
        Damping factor (0 to 1).
    """
    n_safe = np.maximum(n_cgs, 1e-10)  # Prevent division by zero
    return np.power(1.0 + nevac / n_safe, -0.66)
