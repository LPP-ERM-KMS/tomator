def _RRH2_ELAS(Te: np.ndarray) -> np.ndarray:
    """
    H2 elastic + rotational excitation rate coefficient (1D interpolation).
    e + H2 -> e + H2 (vibrationally elastic)
    
    From reactionrates.cpp ELAS case - 1D lookup table.
    
    Parameters
    ----------
    Te : np.ndarray
        Electron temperature [eV].
        
    Returns
    -------
    k : np.ndarray
        Rate coefficient [cm³/s].
    """
    Te = np.atleast_1d(Te)
    original_shape = Te.shape
    Te_flat = Te.flatten()
    
    # Clamp Te to grid bounds (matching C++ bounds check)
    Te_clamped = np.clip(Te_flat, _H2_ELAS_TE_GRID[0], _H2_ELAS_TE_GRID[-1])
    
    # 1D interpolation
    k = np.interp(Te_clamped, _H2_ELAS_TE_GRID, _H2_ELAS_K_TABLE)
    
    # Apply minimum threshold (matching C++ k < 1e-20 -> 0)
    k = np.where(k < 1e-20, 0.0, k)
    
    return k.reshape(original_shape)


