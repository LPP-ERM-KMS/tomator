# Create interpolator for H2 dissociation (lazy initialization)
_h2_diss_interp = None

def _RRH2_DISS(Te: np.ndarray, ne_cgs: np.ndarray) -> np.ndarray:
    """
    H2 electron-impact dissociation rate coefficient from Dirk W. tables.
    e + H2 -> e + H + H
    
    Parameters
    ----------
    Te : np.ndarray
        Electron temperature [eV].
    ne_cgs : np.ndarray
        Electron density [cm^-3].
        
    Returns
    -------
    k : np.ndarray
        Rate coefficient [cm³/s].
    """
    from scipy.interpolate import RegularGridInterpolator
    
    global _h2_diss_interp
    if _h2_diss_interp is None:
        # Create 2D interpolator: axes are (Te, ne), values are k
        _h2_diss_interp = RegularGridInterpolator(
            (_H2_TE_GRID, _H2_NE_GRID),
            _H2_DISS_TABLE,
            method='linear',
            bounds_error=False,
            fill_value=None  # Use nearest for extrapolation
        )
    
    # Ensure arrays
    Te = np.atleast_1d(Te)
    ne_cgs = np.atleast_1d(ne_cgs)
    
    # Clamp to table bounds (matching C++ behavior)
    Te_clamped = np.clip(Te, 0.1, 100.0)
    # C++ uses ne in m^-3, converts to cm^-3 for table: ne*1e6
    # Our input is already in cm^-3, table expects cm^-3
    ne_clamped = np.clip(ne_cgs, 1e-6 * 1e15, 1e-6 * 1e18)  # 1e9 to 1e12 cm^-3
    
    # Interpolate
    points = np.column_stack([Te_clamped.ravel(), ne_clamped.ravel()])
    k = _h2_diss_interp(points)
    
    # Apply minimum threshold (matching C++ k < 1e-20 -> 0)
    k = np.where(k < 1e-20, 0.0, k)
    
    return k.reshape(Te.shape)


