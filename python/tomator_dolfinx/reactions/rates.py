        """
        Electron-impact excitation of atomic hydrogen.
        e + H -> e + H*  (Reaction 2.1.1-2.1.4)
        
        Parameters
        ----------
        Te : np.ndarray
            Electron temperature [eV].
            
        Returns
        -------
        k : np.ndarray
            Rate coefficient [cm³/s].
        """
        k = np.zeros_like(Te)
        mask = Te > 0.6
        Te_safe = np.maximum(Te[mask], 0.6)
        
