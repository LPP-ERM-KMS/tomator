# Minimum rate threshold (from C++ code line 645)
MIN_RATE = 4e-17  # cm³/s - rates below this are set to 0


def _clamp_ne(ne: np.ndarray) -> np.ndarray:
    """Clamp electron density to valid range [1e8, 1e13] cm^-3."""
    return np.clip(ne, 1e8, 1e13)


def _clamp_Te(Te: np.ndarray) -> np.ndarray:
    """Clamp electron temperature to valid range [1, 1000] eV."""
    return np.clip(Te, 1.0, 1000.0)


def _apply_min_rate(k: np.ndarray) -> np.ndarray:
    """Apply minimum rate threshold - rates below MIN_RATE are set to 0."""
    return np.where(k < MIN_RATE, 0.0, k)


