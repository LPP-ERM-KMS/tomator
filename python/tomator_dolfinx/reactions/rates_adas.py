# Create interpolators (using log for ne since it spans many decades)
def _create_interpolator_2d(data: np.ndarray):
    """Create 2D interpolator for (log10(ne), Te) -> rate."""
    log_ne = np.log10(Mne)
    return RegularGridInterpolator(
        (MTe, log_ne), data,
        method='linear', bounds_error=False, fill_value=None
    )


# Pre-create interpolators
_interp_HeI_ion = _create_interpolator_2d(MkHeI_ion_ADAS)
_interp_HeII_ion = _create_interpolator_2d(MkHeII_ion_ADAS)
_interp_HeII_rec = _create_interpolator_2d(MkHeII_rec_ADAS)
_interp_HeIII_rec = _create_interpolator_2d(MkHeIII_rec_ADAS)


def HeI_ionization_ADAS(Te: np.ndarray, ne: np.ndarray) -> np.ndarray:
    """
    HeI ionization rate coefficient using ADAS tables.
    e + He -> e + He+ + e
    
    Parameters
    ----------
    Te : np.ndarray
        Electron temperature [eV].
    ne : np.ndarray
        Electron density [cm^-3].
        
    Returns
    -------
    k : np.ndarray
        Rate coefficient [cm³/s].
    """
    Te_clamped = _clamp_Te(Te)
    ne_clamped = _clamp_ne(ne)
    
    # For Te < 1 eV, rate is 0 (from C++ code)
    k = np.zeros_like(Te)
    mask = Te > 1.0
    
    if np.any(mask):
        points = np.column_stack([Te_clamped[mask], np.log10(ne_clamped[mask])])
        k[mask] = _interp_HeI_ion(points)
    
    return _apply_min_rate(k)


