def He_cooling_rate_ADAS(Te: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Helium cooling rates from ADAS/SOLPS-ITER.
    
    Parameters
    ----------
    Te : np.ndarray
        Electron temperature [eV].
        
    Returns
    -------
    L_HeI : np.ndarray
        Cooling rate from HeI processes [eV*cm³/s].
    L_HeII : np.ndarray
        Cooling rate from HeII processes [eV*cm³/s].
    L_HeIII : np.ndarray
        Cooling rate from HeIII processes [eV*cm³/s] (always 0).
    """
    Te_clamped = _clamp_Te(Te)
    
    # Interpolate from tables (which are in eV*m³/s)
    # Then multiply by 1e6 to get eV*cm³/s (like C++ does)
    L_HeI = np.interp(Te_clamped, MTe, MkHeI_cool_ADAS) * 1e6
    L_HeII = np.interp(Te_clamped, MTe, MkHeII_cool_ADAS) * 1e6
    L_HeIII = np.zeros_like(Te)
    
    return L_HeI, L_HeII, L_HeIII


